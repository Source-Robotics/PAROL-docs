#!/usr/bin/env python3
"""Copy the robot repository's print table into the docs, as it is.

    python tools/sync_print_table.py [--repo PATH] [--check]

Reads the sheet "3D printed parts stats" of Print table/PR_EXCEL.xlsx from a clone of PAROL6-Desktop-robot-arm
(--repo, else $PAROL6_DIR, else a sibling folder of this repository or ../../projects) and writes
docs/includes/generated/print_table.md: the sheet's two note lines as an admonition and its table, every row and
every column, in the sheet's order. docs/build/printing.md includes it with a snippet. Needs openpyxl
(`pip install openpyxl`); --check exits 1 when the file is out of date.
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "includes" / "generated" / "print_table.md"
SHEET = "3D printed parts stats"
XLSX = Path("Print table") / "PR_EXCEL.xlsx"
REPO_URL = "https://github.com/Source-Robotics/PAROL6-Desktop-robot-arm"


def find_repo(arg: str | None) -> Path:
    for c in (arg, os.environ.get("PAROL6_DIR"), ROOT.parent / "PAROL6-Desktop-robot-arm",
              ROOT.parent.parent / "projects" / "PAROL6-Desktop-robot-arm"):
        if c and (Path(c) / XLSX).exists():
            return Path(c)
    sys.exit("sync_print_table: no clone of PAROL6-Desktop-robot-arm found; pass --repo PATH")


def cell(v) -> str:
    if v is None:
        return ""
    if isinstance(v, float):
        return str(int(v)) if v.is_integer() else f"{v:g}"
    return str(v).strip().replace("|", "\\|")


def render(repo: Path) -> str:
    try:
        import openpyxl
    except ImportError:
        sys.exit("sync_print_table: pip install openpyxl")
    ws = openpyxl.load_workbook(repo / XLSX, data_only=True)[SHEET]
    rows = [list(r) for r in ws.iter_rows(values_only=True)]
    head_i = next(i for i, r in enumerate(rows) if "Part name" in r)
    first = rows[head_i].index("Part name")
    notes = [cell(v) for r in rows[:head_i] for v in r if v]
    header = [cell(v) for v in rows[head_i][first:]]
    while header and not header[-1]:
        header.pop()
    width = len(header)
    body = []
    for r in rows[head_i + 1:]:
        vals = [cell(v) for v in r[first:first + width]]
        if not vals or not vals[0]:
            continue
        body.append("| " + " | ".join(vals + [""] * (width - len(vals))) + " |")
    try:
        commit, when = subprocess.run(["git", "-C", str(repo), "log", "-1", "--format=%h %cs", "--", str(XLSX)],
                                      capture_output=True, text=True, check=True).stdout.split()
    except (subprocess.CalledProcessError, ValueError, FileNotFoundError):
        commit, when = "unknown", "today"
    out = [f"<!-- Generated by tools/sync_print_table.py from {XLSX.as_posix()} in {REPO_URL} ({commit}, {when}). "
           "Do not edit: change the spreadsheet, then run the tool again. -->", ""]
    if notes:
        out += ["!!! note", "    " + " ".join(notes), ""]
    out += ["| " + " | ".join(header) + " |", "|" + "---|" * width] + body
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", help="the clone of PAROL6-Desktop-robot-arm")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 when the file is out of date")
    args = ap.parse_args(argv)
    text = render(find_repo(args.repo)).replace("\n", "\r\n")
    if args.check:
        current = OUT.read_bytes().decode("utf-8") if OUT.exists() else ""
        same = current.split("\r\n", 1)[-1] == text.split("\r\n", 1)[-1]   # the header line names the commit
        print("print_table.md is " + ("up to date" if same else "OUT OF DATE: run tools/sync_print_table.py"))
        return 0 if same else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)}: {text.count(chr(10)) - 5} parts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
